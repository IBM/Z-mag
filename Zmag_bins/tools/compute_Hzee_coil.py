"""
compute_Hzee_coil.py

This module contains the class :class:`HFieldCoilBiotSavart` which implements the Biot-Savart law 
to compute the magnetic field generated by a wire path.

The module also provides a helper function to generate the wire path for the coil in the writer (in **clockwise** orientation).

**Magnetic Field Computation**

For a current-carrying wire, the magnetic field H at a position r is given by:

    ``H(r) = N*(I / (4π)) ∫ [dl × (r - r′)] / |r - r′|³``

where:
    - I is the current through the wire
    - dl is the infinitesimal wire segment dl at position r′
    - r′ is the position of the wire segment
    - r is the observation point
    - N no. of coil windings

**Notes on Non-dimensionalization**

- The wire path is assumed to be defined in non-dimensional coordinates normalized by the exchange length `l_ex`:
    - `r*= r / l_ex`
- The wire path is also assumed to be scaled by the same size_scale_fac as the writer geometry:
    - `r** = size_scale_fac * r*`
- The class can output both the physical magnetic field and the non-dimensionalized H field, where the non-dimensional field is scaled using the saturation magnetization of a reference material
    - h = H / Ms_ref

**Workflow**

1. Define the wire path geometry in scaled, non-dimensional coordinates (`r**= size_scale_fac * r / l_ex`).
2. Instantiate :class:`HFieldCoilBiotSavart` with coil parameters and desired current.
3. Use `compute_phys_field` or `compute_non_dim_field` methods to evaluate the magnetic field.

Date: 15.07.2025  
Author: K. Aebischer
"""

import numpy as np

class HFieldCoilBiotSavart:
    """
    Compute the magnetic field H generated by a coil using the Biot–Savart law.

    This class models coil as a wire path with a specified number of turns and current,
    and evaluates the resulting magnetic field at arbitrary spatial positions.
    The class assumes that the positions are provided in non-dimensional units,
    physical length units can be obtained through multiplication with the exchange length.
    The resulting field can be returned in physical units or converted to a dimensionless
    form using the reference value for the saturation magnetization.

    Attributes
    ----------
    wire_path : np.ndarray
        A (3, N) array of points defining the wire geometry.
    N_turns : int
        Number of turns in the coil.
    current : float
        Current in Amperes [A].
    l_ex : float
        Exchange length.
    Ms_ref : float
        Reference saturation magnetization for nondimensionalization.
    size_scale_fac : float
        scaling factor used to scale the geometry
    """

    def __init__(self, wire_path, N_turns, current, l_ex=1, Ms_ref=1, size_scale_fac=1):
        """
        Initialize the coil with a specified wire path and parameters.

        Parameters
        ----------
        wire_path : np.ndarray
            A (3, N) array of 3D points describing the wire path of the coil.
        N_turns : int
            Number of turns in the coil.
        current : float
            Reference current in Amperes [A].
        l_ex : float, optional
            Exchange length used for scaling the computed magnetic field to physical units. Default is 1.
        Ms_ref : float, optional
            Reference magnetization used to convert the physical H field to a dimensionless form. Default is 1.
        size_scale_fac : float
            scaling factor used to scale the geometry

        """
        self.wire_path = wire_path              # Shape (3, N) points describing wire path
        self.N_turns = N_turns                  # int, No. of coil turns
        self.current = current                  # [A] Reference current
        self.l_ex = l_ex                        # Needed for scaling to physical field
        self.Ms_ref = Ms_ref                    # Used for converting H_phys to dimensionless h
        self.size_scale_fac = size_scale_fac    # Scaling factor used for the scaling of the geometry

    def _biot_savart(self, pos, current):
        """
        Compute the magnetic field H at given points using the Biot–Savart law.

        Parameters
        ----------
        pos : np.ndarray
            A (3, N) array of coordinates where the field is evaluated. Each column is a point `[x, y, z]ᵀ`.
        current : float
            Electric current in Amperes [A].

        Returns
        -------
        np.ndarray
            A (3, N) array containing the magnetic field vectors **H** at the specified positions.

        """
        Hfield = np.zeros_like(pos)                              # shape (3, N)
        wire_points = self.wire_path
        for i in range(wire_points.shape[1] - 1):
            dl = wire_points[:, i+1] - wire_points[:, i]        # wire segment
            r0 = (wire_points[:, i+1] + wire_points[:, i]) / 2  # midpoint of segment
            r = pos - r0[:, np.newaxis]                         # position vectors for points of interest     
            r_norm = np.linalg.norm(r, axis=0)
            # Set mask to avoid division by zero
            mask = r_norm > 1e-12  
            r = r[:, mask]
            r_norm = r_norm[mask]                               # shape (3, N_filtered)
            dl_cross_r = np.cross(dl, r.T).T                                      
            Hfield[:, mask] += current / (4 * np.pi) * dl_cross_r / (r_norm ** 3)
        Hfield *= self.N_turns
        return Hfield
    
    def compute_non_dim_field(self, pos, I):
        """
        Compute the dimensionless magnetic field h = H / Ms_ref at given positions.

        Parameters
        ----------
        pos : np.ndarray
            A (3, N) array of evaluation points in non-dimensional coordinates,
            where `r* = r / l_ex`.
        I : float
            Current in Amperes [A].

        Returns
        -------
        np.ndarray
            A (3, N) array containing the dimensionless magnetic field vectors **h**
            at the input positions.

        """
        H_field = self._biot_savart(pos, current=I)                # units: A/m scaled by 1/l_ex
        H_field *= self.size_scale_fac                              # take into account dilation of the geometry
        H_phys = H_field / self.l_ex                               # convert to A/m in physical space
        h = H_phys / self.Ms_ref                                   # non-dimensional field
        return h

    def compute_phys_field(self, pos, I):
        """
        Compute the physical magnetic field H [A/m] at given positions.

        Parameters
        ----------
        pos : np.ndarray
            A (3, N) array of evaluation points in non-dimensional coordinates,
            where `r* = r / l_ex`.
        I : float
            Current in Amperes [A].

        Returns
        -------
        np.ndarray
            A (3, N) array containing the magnetic field H at the specified positions,
            in units of [A/m].
        """
        H_field = self._biot_savart(pos, current=I)                 # units: A/m scaled by 1/l_ex
        H_field *= self.size_scale_fac                              # take into account dilation of the geometry
        H_phys = H_field / self.l_ex                                # convert to A/m in physical space
        return H_phys
    
    


def generate_writer_coil_wire_path(LapDelta, dx=0.1):
    """
    Generate the wire path for an approximation of the physical coil geometry.

    This function reconstructs a simplified wire path for the coil used in the ANSYS model.
    The two volumetric coil bundles are approximated by a single wire path located at their
    surface-area-weighted midpoint.
    The result is returned in physical coordinates (units: micrometer), which can later be non-dimensionalized for use in simulations.

    Note:
        Generates the wire path in **clockwise** orientation.
    
    Parameters
    ----------
    LapDelta : float
        Vertical shift applied to the geometry before trimming at z = 0.
        This compensates for the shift applied to the ANSYS geometry when computing the coil center.
    dx : float, optional
        Resolution of the wire path, i.e., step size along the path. Determines the number of points.
        Default is 0.1.

    Returns
    -------
    np.ndarray
        A (3, N) array representing the wire path in 3D physical space (units in um).
    """

    # location of center point of top coil in ZX plane
    CP_top = np.array([2.8 + 1.8/2, 0, LapDelta + 7.15 + 10.8/2])
    A_top = 19.44
    # location of center point of bottom coil in ZX plane
    CP_bottom = np.array([-1.2 - 1.4/2, 0, LapDelta + 4.7 + 13/2])
    A_bottom = 18.2

    CP_wire = (1/(A_bottom + A_top))*(A_bottom*CP_bottom + A_top*CP_top)
    
    # Lengths of straight segments and radii of circular arcs from ANSYS sketch
    # radii have to adjusted since the CP of the approximate single wire has a position offset
    CP_sketch_z = 13.05
    H18 = 2
    V17 = 4
    r_top = 16.4 + (CP_sketch_z - CP_wire[2])
    r_bottom = 10 + (CP_sketch_z - CP_wire[2])
    length_line_seg1 = H18 + r_top - r_bottom

    CP_arc_b = CP_wire + length_line_seg1*np.array([0,-1,0]) + r_bottom*np.array([0,0,1])
    CP_arc_t = CP_wire + H18*np.array([0,-1,0]) + (r_bottom + V17)*np.array([0,0,1])

    # Generate point coordinates for wire path
    N = length_line_seg1/dx
    wire_points1 = generate_line(CP_wire, CP_wire+length_line_seg1*np.array([0,-1,0]), N)
    length_arc = np.pi/2 * r_bottom
    N = length_arc/dx
    # wire_points2 = generate_arc(CP_arc_b, r_bottom, np.array([1,0,0]), np.pi*(5/4), np.pi, N)
    start_arc = wire_points1[:,-1]
    end_arc = CP_arc_b + r_bottom*np.array([0,-1,0])
    wire_points2 = generate_arc(CP_arc_b, start_arc, end_arc, N)
    N = V17/dx
    start_V17 = CP_arc_b+r_bottom*np.array([0,-1,0])
    end_V17 = start_V17+V17*np.array([0,0,1])
    wire_points3 = generate_line(start_V17, end_V17, N)
    length_arc = np.pi/2 * r_top
    N = length_arc/dx
    # wire_points4 = generate_arc(CP_arc_t, r_top, np.array([1,0,0]), np.pi, np.pi*(1/4), N)
    start_arc = wire_points3[:,-1]
    end_arc = CP_arc_t + r_top*np.array([0,0,1])
    wire_points4 = generate_arc(CP_arc_t, start_arc, end_arc, N)
    N = H18/dx
    start_H18 = CP_arc_t + r_top*np.array([0,0,1])
    end_H18 = start_H18 + H18*np.array([0,1,0])
    wire_points5 = generate_line(start_H18, end_H18, N)

    # Stack all wire segments into one (3, N_total) array
    wire_path_half_sym = np.hstack([wire_points1[:,:-1], wire_points2[:,:-1], wire_points3[:,:-1], wire_points4[:,:-1], wire_points5])

    mirror_path = wire_path_half_sym.copy()
    mirror_path[1,:] *= -1
    mirror_path = mirror_path[:, ::-1]
    wire_path = np.hstack([wire_path_half_sym[:,:-1], mirror_path[:,:]])

    return wire_path

def generate_circular_coil_wire_path(radius, center, normal, num_points=100):
    """
    Generate a wire path representing a circular coil for debugging or example calculations.

    The coil is defined by its radius, center point, and a normal vector specifying the coil orientation.
    The function returns a set of points evenly spaced along the circular path.

    Parameters
    ----------
    radius : float
        Radius of the circular coil.
    center : array-like of shape (3,)
        Coordinates of the center of the coil.
    normal : array-like of shape (3,)
        Normal vector defining the plane of the coil. Will be normalized internally.
    num_points : int, optional
        Number of points to generate along the coil wire path. Default is 100.

    Returns
    -------
    np.ndarray
        Array of shape (3, num_points) containing the coordinates of points along the coil.
    """

    center = np.asarray(center)
    normal = np.asarray(normal)
    normal = normal / np.linalg.norm(normal)  # normalize

    # Parameter theta from 0 to 2pi
    theta = np.linspace(0, -2*np.pi, num_points, endpoint=False)

    # Points in XY plane (circle normal along z)
    circle_pts = np.vstack((radius * np.cos(theta),
                            radius * np.sin(theta),
                            np.zeros(num_points)))  # shape (3, num_points)

    # Rotation from z-axis to normal
    # z-axis unit vector
    z_axis = np.array([0, 0, 1])

    # Compute rotation axis and angle
    v = np.cross(z_axis, normal)
    s = np.linalg.norm(v)
    c = np.dot(z_axis, normal)

    if s == 0:
        # normal is aligned with z_axis, no rotation needed
        R = np.eye(3)
    else:
        # Skew-symmetric cross-product matrix of v
        vx = np.array([[0, -v[2], v[1]],
                    [v[2], 0, -v[0]],
                    [-v[1], v[0], 0]])

        # Rodrigues' rotation formula
        R = np.eye(3) + vx + (vx @ vx) * ((1 - c) / (s ** 2))

    # Rotate points
    rotated_pts = R @ circle_pts

    # Translate to center
    wire_path = rotated_pts + center[:, np.newaxis]  # shape (3, num_points)

    return wire_path


"""
Helper functions to generate wire path
"""

def generate_line(p0, p1, N):
    """
    Generate `N` evenly spaced points along a straight line segment from `p0` to `p1`.

    Parameters
    ----------
    p0 : np.ndarray
        Starting point of the line segment, shape (3,).
    p1 : np.ndarray
        Ending point of the line segment, shape (3,).
    N : int or float
        Number of points to generate along the line. Will be rounded up to nearest integer.

    Returns
    -------
    np.ndarray
        Array of shape (3, N) containing points along the line segment.
    """
    N = int(np.ceil(N))
    return np.linspace(p0, p1, N).T  # shape (3, N)


def generate_arc(cent_arc, start_arc, end_arc, Npoints):
    """
    Generate `Npoints` along a circular arc from `start_arc` to `end_arc`.

    The arc lies on a circle centered at `cent_arc`.

    Parameters
    ----------
    cent_arc : np.ndarray
        Array of shape (3,) specifying the center of the circular arc.
    start_arc : np.ndarray
        Array of shape (3,) specifying the starting point on the arc.
    end_arc : np.ndarray
        Array of shape (3,) specifying the ending point on the arc.
    Npoints : int
        Number of points to generate along the arc, including the start and end points.

    Returns
    -------
    np.ndarray
        A (3, Npoints) array of points along the arc in 3D space.
    """
    Npoints = int(np.ceil(Npoints))
    vec_start = start_arc - cent_arc
    vec_end = end_arc - cent_arc

    r = np.linalg.norm(vec_start)
    if not np.isclose(r, np.linalg.norm(vec_end)):
        raise ValueError("Start and end points must lie on the same circle.")

    # Normal to the plane of the arc
    vec_normal = np.cross(vec_start, vec_end)
    if np.linalg.norm(vec_normal) < 1e-12:
        raise ValueError("Start, end, and center must not be collinear.")
    vec_normal /= np.linalg.norm(vec_normal)

    # Orthonormal basis in the arc plane
    e1 = vec_start / r
    e2 = np.cross(vec_normal, e1)

    # Angle between start and end
    cos_angle = np.dot(vec_start, vec_end) / r**2
    sin_angle = np.dot(np.cross(vec_start, vec_end), vec_normal) / r**2
    angle = np.arctan2(sin_angle, cos_angle)

    # Sample angles
    thetas = np.linspace(0, angle, Npoints)
    points = cent_arc[:, np.newaxis] + r * (np.outer(e1, np.cos(thetas)) + np.outer(e2, np.sin(thetas)))

    return points  # shape (3, Npoints)
